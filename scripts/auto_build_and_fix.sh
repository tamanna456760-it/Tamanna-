#!/usr/bin/env bash
# Install the declared server/test requirements, compile Python sources, and run tests.
set -Eeuo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

PYTHON_BIN="${PYTHON:-python3}"
command -v "$PYTHON_BIN" >/dev/null 2>&1 || {
  echo "ERROR: Python is required (set PYTHON=/path/to/python if needed)." >&2
  exit 127
}
command -v bash >/dev/null 2>&1 || {
  echo "ERROR: bash is required." >&2
  exit 127
}

# requirements-test.txt includes requirements-server.txt and the test runner.
echo "[Tamanna] Installing server and test requirements..."
"$PYTHON_BIN" -m pip install -r requirements-test.txt

# Keep generated bytecode outside the repository so this check is non-destructive.
CACHE_DIR="$(mktemp -d "${TMPDIR:-/tmp}/tamanna-pycache.XXXXXX")"
trap 'rm -rf "$CACHE_DIR"' EXIT
export PYTHONPYCACHEPREFIX="$CACHE_DIR"

echo "[Tamanna] Compiling all Python files..."
while IFS= read -r -d '' file; do
  "$PYTHON_BIN" -m py_compile "$file"
done < <(find . \
  -type d \( -name .git -o -name .venv -o -name venv -o -name node_modules -o -name __pycache__ \) -prune \
  -o -type f -name '*.py' -print0)

echo "[Tamanna] Running pytest..."
"$PYTHON_BIN" -m pytest -q

echo "[Tamanna] Build and test checks completed successfully."
